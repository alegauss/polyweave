// The drift gate on the generated module. `src/lib/roadmap.generated.ts` is committed,
// because roadkeep is not (`.gitignore` holds `.roadkeep`) and a clean checkout still has
// to build. Committed means it can go stale, so this is the check that it has not.
//
// Two modes, and which one runs depends on whether roadkeep is on this machine:
//
//   - reachable: regenerate into memory and assert it is byte-identical to the committed
//     file. That catches a roadmap line added, shipped, renumbered or reworded without a
//     `npm run generate`.
//   - not reachable (a clean CI checkout): check the committed module against itself —
//     unique ids, every dependency resolving, every block letter declared. Weaker, and it
//     still refuses the failures that a hand edit of a generated file would produce.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { generatedPath, readRoadkeep, renderModule, waitingOn } from "./roadmap.mjs";

const committed = readFileSync(generatedPath, "utf8");
const read = readRoadkeep();

test("the generated module says it is generated", () => {
  assert.match(committed, /^\/\/ GENERATED by scripts\/roadmap\.mjs/);
});

test(
  "the generated module matches the roadmap",
  { skip: read ? false : "roadkeep is not reachable on this machine" },
  () => {
    assert.equal(
      renderModule(read),
      committed,
      "src/lib/roadmap.generated.ts is out of date — run `npm run generate`",
    );
  },
);

// --- the self-consistency checks, which run either way ---

const ids = [...committed.matchAll(/^    id: "([^"]+)",$/gm)].map((m) => m[1]);
const blockOf = [...committed.matchAll(/^    block: "([^"]+)",$/gm)].map((m) => m[1]);
const declared = [...committed.matchAll(/\{ block: "([^"]+)", title:/g)].map((m) => m[1]);
const deps = [...committed.matchAll(/^    deps: \[([^\]]*)\],$/gm)]
  .flatMap((m) => m[1].split(",").map((s) => s.trim().replace(/"/g, "")))
  .filter(Boolean);
const paused = (committed.match(/^export const generatedPaused: string\[\] = \[([^\]]*)\];$/m)?.[1] ?? "")
  .split(",")
  .map((s) => s.trim().replace(/"/g, ""))
  .filter(Boolean);

test("the module has lines, blocks and non-goals at all", () => {
  assert.ok(ids.length > 0, "no tasks in the generated module");
  assert.ok(declared.length > 0, "no blocks in the generated module");
  assert.match(committed, /generatedNonGoals: GeneratedNonGoal\[\] = \[\s*\{/);
});

test("every id appears once", () => {
  assert.equal(new Set(ids).size, ids.length, "a task id appears twice");
});

test("every task sits in a declared block", () => {
  assert.equal(blockOf.length, ids.length, "a task has no block");
  for (const b of new Set(blockOf)) {
    assert.ok(declared.includes(b), `block ${b} has lines but is not declared`);
  }
});

test("every dependency names a line that exists", () => {
  // The backlog is the roadmap and the deferred store. A line that was set aside keeps
  // its id and is still waited on, so "not in the roadmap" is not the same claim as
  // "nothing declares it" — and only the second is a defect.
  const known = new Set([...ids, ...paused]);
  for (const d of new Set(deps)) {
    assert.ok(known.has(d), `${d} is depended on and nothing declares it`);
  }
});

test("a line that was set aside is not also open", () => {
  for (const id of paused) {
    assert.ok(!ids.includes(id), `${id} is both paused and in the roadmap`);
  }
});

test("a dependency that has shipped is no longer waited on", () => {
  // roadkeep annotates a resolved dep in place, as `PW5 ✅`. Carrying that through
  // would print "waits on PW5 ✅" on a line that waits on nothing, and would make the
  // check above look for an id that left the roadmap when it shipped.
  assert.deepEqual(waitingOn(["PW5 ✅"]), []);
  assert.deepEqual(waitingOn(["PW9 🗑"]), []);
  assert.deepEqual(waitingOn(["PW7", "PW5 ✅", "PW8"]), ["PW7", "PW8"]);
  assert.deepEqual(waitingOn(undefined), []);
});
